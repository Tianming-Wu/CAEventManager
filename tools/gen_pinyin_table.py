from pypinyin import pinyin, Style

buckets = {}
for cp in range(0x4E00, 0xA000):
    ch = chr(cp)
    try:
        syl = pinyin(ch, style=Style.NORMAL, heteronym=False, errors="ignore")
    except Exception:
        continue
    if not syl or not syl[0]:
        continue
    s = syl[0][0]
    if not s or not s.isalpha():
        continue
    buckets.setdefault(s.lower(), []).append(ch)

parts = ["%s:%s" % (syl, "".join(buckets[syl])) for syl in sorted(buckets)]

